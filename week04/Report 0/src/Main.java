void main() {
    // 1. 'A' / 3 (65 / 3)
    System.out.println("'A' / 3 = " + ('A' / 3));

    // 2. 'A' / 3L (65L / 3L)
    System.out.println("'A' / 3L = " + ('A' / 3L));

    // 3. 1 + 3L
    System.out.println("1 + 3L = " + (1 + 3L));

    // 4. 1.0 / 3
    System.out.println("1.0 / 3 = " + (1.0 / 3));

    // 5. 1 / 3.0
    System.out.println("1 / 3.0 = " + (1 / 3.0));

    // 6. 1.0F / 3
    System.out.println("1.0F / 3 = " + (1.0F / 3));
}